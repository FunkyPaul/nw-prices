def normalize(lang):
    lang = (lang or '').lower()[:2]
    return lang if lang in LANGS else DEFAULT_LANG


def t(key, lang=DEFAULT_LANG, **params):
    entry = STRINGS.get(key)
    if entry is None:
        return key
    text = entry[LANGS.index(normalize(lang))]
    return text.format(**params) if params else text


def js_strings(lang):
    i = LANGS.index(normalize(lang))
    return {k: v[i] for k, v in STRINGS.items() if k.startswith(JS_PREFIXES)}


def cli_lang():
    return normalize(os.environ.get('NWP_LANG', DEFAULT_LANG))
